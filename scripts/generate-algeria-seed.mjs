// Fetches the verified Algeria administrative-division dataset and emits
// a SQL seed file populating the generic regions/cities tables, scoped to
// Algeria via a country_id subquery (no hardcoded UUID needed).
// Run with: node scripts/generate-algeria-seed.mjs

import { writeFileSync } from "node:fs";

const SOURCE_URL =
  "https://raw.githubusercontent.com/ihahachi/Algeria-Cities/main/json/algeria_cities.json";
const ALGERIA_ID_SQL = "(select id from public.countries where iso_code = 'DZ')";

function sqlQuote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJsonb(obj) {
  return `${sqlQuote(JSON.stringify(obj))}::jsonb`;
}

async function main() {
  const rows = await fetch(SOURCE_URL).then((r) => r.json());
  if (rows.length !== 1541) {
    console.warn(
      `Warning: expected 1541 communes, source returned ${rows.length}. Continuing anyway.`,
    );
  }

  const wilayas = new Map(); // wilaya_code -> { nameFr, nameAr }
  for (const r of rows) {
    const code = String(r.wilaya_code).padStart(2, "0");
    if (!wilayas.has(code)) {
      wilayas.set(code, { nameFr: r.wilaya_name_fr, nameAr: r.wilaya_name });
    }
  }
  if (wilayas.size !== 69) {
    console.warn(
      `Warning: expected 69 wilayas, source returned ${wilayas.size}. Continuing anyway.`,
    );
  }

  const lines = [];
  lines.push("-- Generated by scripts/generate-algeria-seed.mjs -- do not hand-edit.");
  lines.push("-- Region.default_name is French (Algeria's administrative reference");
  lines.push("-- language); translations carries the Arabic name.");
  lines.push("");
  lines.push("INSERT INTO public.regions (country_id, code, default_name, translations) VALUES");
  lines.push(
    [...wilayas.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([code, w]) =>
          `  (${ALGERIA_ID_SQL}, ${sqlQuote(code)}, ${sqlQuote(w.nameFr)}, ${sqlJsonb({ ar: w.nameAr })})`,
      )
      .join(",\n") + ";",
  );
  lines.push("");
  lines.push(
    "INSERT INTO public.cities (region_id, default_name, translations, postal_code) VALUES",
  );
  lines.push(
    rows
      .map((r) => {
        const code = String(r.wilaya_code).padStart(2, "0");
        const postal = r.code_commune != null ? sqlQuote(String(r.code_commune)) : "NULL";
        const regionSubquery = `(select id from public.regions where country_id = ${ALGERIA_ID_SQL} and code = ${sqlQuote(code)})`;
        return `  (${regionSubquery}, ${sqlQuote(r.commune_name_fr)}, ${sqlJsonb({ ar: r.commune_name })}, ${postal})`;
      })
      .join(",\n") + ";",
  );

  writeFileSync(
    "supabase/migrations/20260813020100_seed_regions_cities.sql",
    lines.join("\n") + "\n",
  );
  console.log(`Wrote ${wilayas.size} regions and ${rows.length} cities.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
