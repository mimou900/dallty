// Fetches verified country + timezone datasets and emits a SQL seed file.
// Run with: node scripts/generate-country-seed.mjs

import { writeFileSync } from "node:fs";

const COUNTRIES_URL =
  "https://raw.githubusercontent.com/mledoze/countries/master/dist/countries-unescaped.json";
const TZ_URL =
  "https://raw.githubusercontent.com/manuelmhtr/countries-and-timezones/master/src/data.json";

function sqlQuote(value) {
  if (value == null) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJsonb(obj) {
  return `${sqlQuote(JSON.stringify(obj))}::jsonb`;
}

async function main() {
  const [countries, tzData] = await Promise.all([
    fetch(COUNTRIES_URL).then((r) => r.json()),
    fetch(TZ_URL).then((r) => r.json()),
  ]);

  // Invert the timezone map: country code -> primary IANA timezone.
  // Prefer a timezone whose country list is exactly [code] (unambiguous);
  // fall back to the first match otherwise.
  const primaryTz = new Map();
  for (const [tzName, info] of Object.entries(tzData.timezones)) {
    for (const code of info.c ?? []) {
      const exclusive = info.c.length === 1;
      if (!primaryTz.has(code) || exclusive) primaryTz.set(code, tzName);
    }
  }

  const currencyRows = new Map(); // code -> {name, symbol}
  const countryRows = [];

  for (const c of countries) {
    const currencyCodes =
      c.currencies && !Array.isArray(c.currencies) ? Object.keys(c.currencies) : [];
    if (!c.cca2 || !currencyCodes.length || !c.callingCodes?.length) continue;
    const currencyCode = currencyCodes[0];
    const currencyInfo = c.currencies[currencyCode];
    if (!currencyRows.has(currencyCode)) {
      currencyRows.set(currencyCode, {
        name: currencyInfo.name,
        symbol: currencyInfo.symbol ?? currencyCode,
      });
    }
    const timezone = primaryTz.get(c.cca2);
    if (!timezone) continue; // skip the handful of territories with no timezone match
    const name = c.name.common;
    const nameFr = c.translations?.fra?.common;
    const nameAr = c.translations?.ara?.common;
    const translations = {};
    if (nameFr && nameFr !== name) translations.fr = nameFr;
    if (nameAr && nameAr !== name) translations.ar = nameAr;

    countryRows.push({
      isoCode: c.cca2,
      defaultName: name,
      translations,
      currencyCode,
      callingCode: c.callingCodes[0].startsWith("+") ? c.callingCodes[0] : `+${c.callingCodes[0]}`,
      timezone,
      flag: c.flag,
      displayOrder: c.cca2 === "DZ" ? 0 : 100,
    });
  }

  countryRows.sort(
    (a, b) => a.displayOrder - b.displayOrder || a.defaultName.localeCompare(b.defaultName),
  );

  const lines = [];
  lines.push("-- Generated by scripts/generate-country-seed.mjs -- do not hand-edit.");
  lines.push("-- Re-run only against an empty currencies/countries table (e.g. a fresh");
  lines.push("-- database replaying every migration) -- this is not idempotent against");
  lines.push("-- the already-seeded live project.");
  lines.push("");
  lines.push("INSERT INTO public.currencies (code, name, symbol) VALUES");
  lines.push(
    [...currencyRows.entries()]
      .map(([code, v]) => `  (${sqlQuote(code)}, ${sqlQuote(v.name)}, ${sqlQuote(v.symbol)})`)
      .join(",\n") + ";",
  );
  lines.push("");
  lines.push(
    "INSERT INTO public.countries (iso_code, default_name, translations, currency_code, calling_code, timezone, flag, display_order) VALUES",
  );
  lines.push(
    countryRows
      .map(
        (c) =>
          `  (${sqlQuote(c.isoCode)}, ${sqlQuote(c.defaultName)}, ${sqlJsonb(c.translations)}, ${sqlQuote(c.currencyCode)}, ${sqlQuote(c.callingCode)}, ${sqlQuote(c.timezone)}, ${sqlQuote(c.flag)}, ${c.displayOrder})`,
      )
      .join(",\n") + ";",
  );

  writeFileSync("scripts/output/seed-currencies-countries.sql", lines.join("\n") + "\n");
  console.log(`Wrote ${currencyRows.size} currencies and ${countryRows.length} countries.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
